import assert from "node:assert/strict";
import { mkdtemp, readdir, readFile, realpath, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Readable } from "node:stream";
import test from "node:test";
import { fetchRemoteSourceText } from "../src/remote-json-source.js";
import { parseEastGreenwichCandidateCapture } from "../src/state-ballot-east-greenwich-collection.js";
import { configuredStateBallotSources, legacyReviewedStateBallotSource } from "../src/state-ballot-registry.js";
import { createStateBallotRepository } from "../src/state-ballot-repository.js";
import { createStateBallotStorage } from "../src/state-ballot-storage.js";
import { eastGreenwichDiscoveryFixture, eastGreenwichFixtureTime } from "./helpers/east-greenwich-collection-fixture.js";

test("access challenges preserve reviewed records and clocks, report access rather than format errors and recover normally", async (context) => {
	const directory = await realpath(await mkdtemp(join(tmpdir(), "ballot-access-challenge-")));
	context.after(() => rm(directory, { recursive: true, force: true }));
	const source = configuredStateBallotSources.find(source => source.id === "ri-east-greenwich-2026")!;
	const capture = JSON.stringify({ schemaVersion: 1, type: "east-greenwich-candidate-capture", discovery: eastGreenwichDiscoveryFixture(), electionDate: source.electionDate });
	const parsed = parseEastGreenwichCandidateCapture(source, capture, eastGreenwichFixtureTime);
	const reviewed = { ...parsed, source: legacyReviewedStateBallotSource(source)!, collectionIndexSha256: undefined };
	const storage = createStateBallotStorage(directory);
	await storage.write(reviewed);
	const accepted = await storage.read(source);
	assert.ok(accepted);
	const file = join(directory, (await readdir(directory)).find(name => name.startsWith(source.id))!);
	const before = await readFile(file);
	let clock = eastGreenwichFixtureTime;
	let blocked = true;
	let requests = 0;
	const repository = createStateBallotRepository({ sources: [source], dataDirectory: directory, refreshReviewedLegacy: true, now: () => clock, fetchText: async () => {
		requests++;
		if (!blocked) return capture;
		return fetchRemoteSourceText("https://example.com/elections", { allowedHosts: ["example.com"], resolveAddresses: async () => [{ address: "93.184.216.34", family: 4 }], transport: async () => ({ statusCode: 200, headers: { "content-type": "text/html" }, body: Readable.from(["<html><body><iframe id='main-iframe' src='/_Incapsula_Resource?synthetic'>Request unsuccessful. Incapsula incident ID: synthetic</iframe></body></html>"]) }) });
	} });
	const fallback = await repository.getSnapshot("RI");
	assert.deepEqual(fallback, accepted);
	assert.deepEqual(await readFile(file), before);
	const observation = (await repository.inspectSources!())[0]!;
	assert.equal(observation.failure, "Publisher access challenge requires review.");
	assert.equal(observation.retrievedAt, reviewed.retrievedAt);
	assert.equal(observation.records, reviewed.records.length);
	assert.equal(observation.lastImportAt, null);
	assert.equal(requests, 1);
	assert.deepEqual(await repository.getSnapshot("RI"), accepted);
	assert.equal(requests, 1);
	blocked = false;
	clock += 5 * 60 * 1000;
	const restored = await repository.getSnapshot("RI");
	assert.deepEqual(restored?.records, reviewed.records);
	assert.equal(restored?.retrievedAt, reviewed.retrievedAt);
	assert.equal((await repository.inspectSources!())[0]!.failure, null);
	assert.equal(requests, 2);
});
